// Generates supabase/seed.sql from the starter catalog in src/data/products.ts.
// Run: node --experimental-strip-types scripts/gen-seed.ts
import { writeFileSync } from "node:fs";
import { products } from "../src/data/products.ts";

const q = (s: string | null | undefined) => (s == null ? "null" : `'${s.replace(/'/g, "''")}'`);
const j = (o: unknown) => `${q(JSON.stringify(o))}::jsonb`;
const arr = (a: string[] = []) => `array[${a.map(q).join(",")}]::text[]`;

let sql = `-- Starter catalog for Arganista (generated by scripts/gen-seed.ts).
-- Run in Supabase → SQL Editor after 0001_shop.sql. Safe to re-run: existing slugs are skipped.
begin;
`;

products.forEach((p, i) => {
  sql += `
with p as (
  insert into products (slug, category, ingredients, badges, name, tagline, description, how_to, key_ingredients, tint, position)
  values (${q(p.slug)}, ${q(p.category)}, ${arr(p.ingredients)}, ${arr(p.badges)}, ${j(p.name)}, ${j(p.tagline)}, ${j(p.description)}, ${j(p.howTo)}, ${j(p.keyIngredients)}, ${q(p.tint)}, ${i})
  on conflict (slug) do nothing
  returning id
), v as (
  insert into product_variants (product_id, code, label, price, in_stock, image_url, position)
  select p.id, x.code, x.label, x.price, true, x.image_url, x.pos from p, (values
    ${p.variants.map((v, k) => `(${q(v.id)}, ${q(v.label ?? null)}, ${v.price}::numeric, ${q(p.variantImages?.[v.id] ?? null)}, ${k})`).join(",\n    ")}
  ) as x(code, label, price, image_url, pos)
  returning 1
)
insert into product_images (product_id, url, position)
select p.id, x.url, x.pos from p, (values
  ${p.images.map((u, k) => `(${q(u)}, ${k})`).join(",\n  ")}
) as x(url, pos);
`;
});

sql += "\ncommit;\n";
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`seed.sql written (${products.length} products)`);
